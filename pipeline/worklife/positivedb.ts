/** 見出しが想定と1つでも違えば例外で止める。読み進めない。 */
export function assertHeader(header: readonly string[]): void {
  if (header.length !== EXPECTED_HEADER.length) {
    throw new HeaderMismatchError(
      `女性活躍DBの列数が想定と違います: ${EXPECTED_HEADER.length}列の想定に対して${header.length}列`
    );
  }
  for (let i = 0; i < EXPECTED_HEADER.length; i++) {
    if (header[i] !== EXPECTED_HEADER[i]) {
      throw new HeaderMismatchError(
        `女性活躍DBの${i + 1}列目が想定と違います: "${EXPECTED_HEADER[i]}" の想定に対して "${header[i]}"`
      );
    }
  }
}

/** 雇用管理区分ごとの値。**平均して1つにしない**（区分は自由記述で、正社員と派遣が並ぶ） */
export type UnitValue = { unit: string; value: number | null };

export type WorklifeRecord = {
  corporateNumber: string;
  positivedbName: string;
  /** 一月当たりの平均残業時間（時間）。公表項目6 */
  overtimeAll: number | null;
  /** 「対象正社員」「その他」「基幹的な職種」のいずれか */
  overtimeScope: string;
  /** 公表項目7。**6と7の両方を見ないと4割落とす** */
  overtimeUnits: UnitValue[];
  /** 年次有給休暇の取得率（%）。公表項目8(1) */
  paidLeaveAll: number | null;
  /** 公表項目8(2) */
  paidLeaveUnits: UnitValue[];
  /** 男女の賃金の差異（%）＝ 女性の平均賃金 ÷ 男性の平均賃金 × 100。公表項目14 */
  wageGapAll: number | null;
  wageGapRegular: number | null;
  wageGapNonRegular: number | null;
  /** 賃金の差異の対象期間（`2025年4月1日～2026年3月31日` 等） */
  wageGapPeriod: string;
  /** 会社が登録した自由記述。差異の主因の説明。718社が持つ */
  wageGapNote: string;
  /** データ集計時点（`2026年3月時点` 等）。有報の決算期とは別の時点 */
  asOf: string;
  updatedAt: string;
};

/** 落とした異常値。**黙って消さない**ので、呼び出し側がサマリーに出す。 */
export type DroppedValue = { corporateNumber: string; name: string; field: string; raw: string };

/**
 * 数値として読む。**空文字・`-`・「非公表」は `null`。`0` とは区別する。**
 * 未登録と「残業0時間」を同じ値にすると、読者が見分けられない。
 */
export function toNumber(raw: string): number | null {
  const t = (raw ?? "").trim();
  if (t === "") return null;
  return /^-?\d+(\.\d+)?$/.test(t) ? Number(t) : null;
}

function units(row: readonly string[], nameIdx: readonly number[], valueIdx: readonly number[]): UnitValue[] {
  const out: UnitValue[] = [];
  for (let k = 0; k < nameIdx.length; k++) {
    const unit = (row[nameIdx[k]] ?? "").trim();
    const value = toNumber(row[valueIdx[k]] ?? "");
    if (unit !== "" || value !== null) out.push({ unit, value });
  }
  return out;
}

/**
 * 1行を取り込む形に直す。
 *
 * **異常値の扱いは項目ごとに違う**（spec.md 1.4）。
 * - 負の残業時間は入力ミス以外にありえないので落とす（実測で1社・`-16.8`）
 * - 100%を超える有給取得率は落とさない（前年繰越の消化。実測で7社）
 * - 極端な賃金の差異も落とさない（少人数区分の外れ値だが値としては正しい）
 */
export function normalizeRow(row: readonly string[]): { record: WorklifeRecord; dropped: DroppedValue[] } {
  const corporateNumber = (row[COL.corporateNumber] ?? "").trim();
  const positivedbName = (row[COL.name] ?? "").trim();
  const dropped: DroppedValue[] = [];

  let overtimeAll = toNumber(row[COL.overtimeAll] ?? "");
  if (overtimeAll !== null && overtimeAll < 0) {
    dropped.push({
      corporateNumber,
      name: positivedbName,
      field: "overtime_all",
      raw: (row[COL.overtimeAll] ?? "").trim(),
    });
    overtimeAll = null;
  }

  const overtimeUnits = units(row, COL.overtimeUnitName, COL.overtimeUnitValue).map((u) => {
    if (u.value !== null && u.value < 0) {
      dropped.push({ corporateNumber, name: positivedbName, field: `overtime_unit:${u.unit}`, raw: String(u.value) });
      return { unit: u.unit, value: null };
    }
    return u;
  });

  return {
    record: {
      corporateNumber,
      positivedbName,
      overtimeAll,
      overtimeScope: (row[COL.overtimeScope] ?? "").trim(),
      overtimeUnits,
      paidLeaveAll: toNumber(row[COL.paidLeaveAll] ?? ""),
      paidLeaveUnits: units(row, COL.paidLeaveUnitName, COL.paidLeaveUnitValue),
      wageGapAll: toNumber(row[COL.wageGapAll] ?? ""),
      wageGapRegular: toNumber(row[COL.wageGapRegular] ?? ""),
      wageGapNonRegular: toNumber(row[COL.wageGapNonRegular] ?? ""),
      wageGapPeriod: (row[COL.wageGapPeriod] ?? "").trim(),
      wageGapNote: (row[COL.wageGapNote] ?? "").trim(),
      asOf: (row[COL.asOf] ?? "").trim(),
      updatedAt: (row[COL.updatedAt] ?? "").trim(),
    },
    dropped,
  };
}

/** その会社が3指標のいずれかを持つか。1つも無ければ CSV に行を作らない。 */
export function hasAnyMetric(r: WorklifeRecord): boolean {
  return (
    r.overtimeAll !== null ||
    r.overtimeUnits.some((u) => u.value !== null) ||
    r.paidLeaveAll !== null ||
    r.paidLeaveUnits.some((u) => u.value !== null) ||
    r.wageGapAll !== null
  );
}
