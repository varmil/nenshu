import { formatManYen } from "./format";

/**
 * ランキングの脚注。PC の表の `caption` とモバイルの行の一覧の末尾が同じ文を出す。
 *
 * **書くのは画面のほかの場所に説明が無いものだけ**——年収バーの基準（spec 1.11・
 * AC-13）と、偏差値が100を超えうる理由（spec 1.12・glossary）。
 *
 * **表示基準の断りは置かない。** 以前は実測値なら「有価証券報告書の平均年間給与
 * （提出会社単体）そのままです。年齢の違いは補正していません。」、年齢そろえなら
 * 「推定年収は年齢補正後の推定値です。…」を先頭に置いていたが、どちらも同じ画面に
 * すでにある——出典はリード文（`lead.ts`）と列見出し「平均年収（有報）」、補正の
 * 有無と「推定」は並べ方の帯のヒント（AC-9）。脚注は30行ぶん下にあるので視界では
 * 重ならないが、1画面に同じ断りが3回ある状態だった。**このため脚注は表示基準に
 * よらず同じ文になる。**
 *
 * 「水準は順位と併せて読んでください」も外した。順位のバッジは同じ行にある。
 *
 * `mean` が無い（母集団の統計が引けない）ときは縦線も偏差値も出ないので、帯の
 * 1文だけにする。
 */
export function rankingFootnote(mean: number | null): string {
  const bar = "帯はこのページの1位を100%とした長さ";
  if (mean === null) return `${bar}です。`;
  return (
    `${bar}で、縦線は全体平均（${formatManYen(mean)}）です。` +
    "偏差値は、平均から大きく離れた高年収の会社があるため100を超えることがあります。"
  );
}
