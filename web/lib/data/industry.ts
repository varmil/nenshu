/**
 * 業種名（東証33業種）を**狭い器に収めるための略称**に置き換える1か所。
 *
 * **既定は原文のまま。** 略称は「原文では1行に収まらない」ことが実測で分かった
 * 業種だけに置く。業種名は掲載データの値であって我々が名付けたものではないので、
 * **短くする理由が器の側にあるときだけ、その器の都合として短くする。**
 *
 * いま使うのは企業詳細ページのレーダーの指標リスト（P1）で、`稼ぐ力` の行に
 * 添える `<業種>の中央値 1,126万円` の1か所だけ。**同じ画面のパンくず・見出し・
 * 業界内順位は原文のまま**なので、読者は略称と原文を同じ画面で突き合わせられる。
 *
 * **上限は8文字**（`MAX_LABEL_LENGTH`）。指標リストの2行目は 296px で、左に
 * `1人当たり経常利益`（実測 96.3px）が入るため、注記に使えるのは **191.8px**。
 * `ガラス・土石製品の中央値 318万円` が 179.5px、`証券、商品先物取引業の中央値
 * 598万円` が 201px で、**8文字までなら収まり、10文字では溢れる**（実測）。
 * `industry.test.ts` が実データの33業種すべてを上限と突き合わせる——**データ側に
 * 長い業種名が増えたら、その時点でテストが落ちる。**
 */

/** 略称に置き換える業種。**鍵は `companies.industries` に実在する綴りで書く。** */
const SHORT_LABELS: Record<string, string> = {
  /*
   * `証券、商品先物取引業`（10文字・201px）だけが収まらない。**落とすのは
   * 「取引業」の3文字だけ**にして、読点は中黒に替える——`証券・商品` まで
   * 縮めると「商品」が何を指すか原文から離れる（東証の業種名は
   * 「商品先物取引業」で一続きの語）。
   */
  "証券、商品先物取引業": "証券・商品先物",
};

/** 略称を置くかどうかの線。**器の実測から決めた値**（上のコメント参照）。 */
export const MAX_INDUSTRY_LABEL_LENGTH = 8;

/** 業種名を狭い器向けの表記にする。表に無ければ原文をそのまま返す。 */
export function shortIndustryLabel(tse33: string): string {
  return SHORT_LABELS[tse33] ?? tse33;
}

/** テスト用。表そのものを読めるようにしておく（写しを作らせない）。 */
export const INDUSTRY_SHORT_LABELS: Readonly<Record<string, string>> = SHORT_LABELS;
